CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL CHECK (btrim(name) <> ''),
    kind varchar(10) NOT NULL CHECK (kind IN ('stem', 'bouquet')),
    price numeric(10, 2) NOT NULL CHECK (price >= 0 AND price <> 'NaN'::numeric),
    image_url text NOT NULL CHECK (btrim(image_url) <> ''),
    description text,
    composition text,
    delivery_time varchar(60),
    rating numeric(2, 1) CHECK (rating BETWEEN 0 AND 5),
    display_order integer CHECK (display_order >= 0),
    stock_quantity integer CHECK (stock_quantity >= 0),
    active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX products_active_display_idx ON products (display_order, id) WHERE active;

CREATE TABLE product_origins (
    product_id bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    origin varchar(80) NOT NULL CHECK (btrim(origin) <> ''),
    PRIMARY KEY (product_id, origin)
);

CREATE TABLE tags (
    code varchar(40) PRIMARY KEY,
    label varchar(60) NOT NULL CHECK (btrim(label) <> '')
);

CREATE TABLE product_tags (
    product_id bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    tag_code varchar(40) NOT NULL REFERENCES tags (code) ON DELETE CASCADE,
    PRIMARY KEY (product_id, tag_code)
);

CREATE INDEX product_tags_tag_idx ON product_tags (tag_code, product_id);

CREATE TABLE occasions (
    code varchar(40) PRIMARY KEY,
    label varchar(60) NOT NULL CHECK (btrim(label) <> ''),
    description text NOT NULL,
    image_url text NOT NULL
);

CREATE TABLE occasion_tags (
    occasion_code varchar(40) NOT NULL REFERENCES occasions (code) ON DELETE CASCADE,
    tag_code varchar(40) NOT NULL REFERENCES tags (code) ON DELETE CASCADE,
    PRIMARY KEY (occasion_code, tag_code)
);

CREATE INDEX occasion_tags_tag_idx ON occasion_tags (tag_code);

CREATE TABLE accounts (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL CHECK (btrim(name) <> ''),
    email varchar(254) NOT NULL CHECK (email = btrim(email) AND email <> ''),
    password_hash varchar(255) NOT NULL CHECK (btrim(password_hash) <> ''),
    role varchar(10) NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX accounts_email_unique_idx ON accounts (lower(email));

CREATE TABLE favorites (
    account_id bigint NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    product_id bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (account_id, product_id)
);

CREATE INDEX favorites_product_idx ON favorites (product_id);

CREATE TABLE carts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    account_id bigint UNIQUE REFERENCES accounts (id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE cart_items (
    cart_id uuid NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    product_id bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    quantity integer NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (cart_id, product_id)
);

CREATE INDEX cart_items_product_idx ON cart_items (product_id);

CREATE TABLE orders (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    account_id bigint REFERENCES accounts (id) ON DELETE SET NULL,
    status varchar(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'confirmed', 'preparing', 'shipped', 'delivered', 'cancelled')),
    recipient_name varchar(100) NOT NULL CHECK (btrim(recipient_name) <> ''),
    contact_email varchar(254) NOT NULL CHECK (contact_email = btrim(contact_email) AND contact_email <> ''),
    street_address varchar(150) NOT NULL CHECK (btrim(street_address) <> ''),
    city varchar(100) NOT NULL CHECK (btrim(city) <> ''),
    postal_code varchar(12) NOT NULL CHECK (btrim(postal_code) <> ''),
    country_code varchar(2) NOT NULL DEFAULT 'IT' CHECK (country_code ~ '^[A-Z]{2}$'),
    gift_message varchar(200),
    shipping_price numeric(10, 2) NOT NULL DEFAULT 0
        CHECK (shipping_price >= 0 AND shipping_price <> 'NaN'::numeric),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT orders_italian_postal_code CHECK (country_code <> 'IT' OR postal_code ~ '^[0-9]{5}$')
);

CREATE INDEX orders_account_created_idx ON orders (account_id, created_at DESC);
CREATE INDEX orders_status_created_idx ON orders (status, created_at DESC);

CREATE TABLE order_items (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id bigint REFERENCES products (id) ON DELETE SET NULL,
    product_name varchar(120) NOT NULL CHECK (btrim(product_name) <> ''),
    product_kind varchar(10) NOT NULL CHECK (product_kind IN ('stem', 'bouquet')),
    unit_price numeric(10, 2) NOT NULL CHECK (unit_price >= 0 AND unit_price <> 'NaN'::numeric),
    quantity integer NOT NULL CHECK (quantity > 0),
    line_total numeric(20, 2) GENERATED ALWAYS AS (unit_price * quantity) STORED,
    UNIQUE (order_id, product_id)
);

CREATE INDEX order_items_product_idx ON order_items (product_id);

CREATE VIEW order_totals AS
SELECT
    o.id AS order_id,
    COALESCE(SUM(i.quantity), 0) AS item_count,
    COALESCE(SUM(i.line_total), 0.00) AS subtotal,
    o.shipping_price,
    COALESCE(SUM(i.line_total), 0.00) + o.shipping_price AS total
FROM orders AS o
LEFT JOIN order_items AS i ON i.order_id = o.id
GROUP BY o.id, o.shipping_price;
